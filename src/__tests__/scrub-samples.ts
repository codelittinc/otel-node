/** Deterministic pseudo-random strings over the characters every pattern turns on. */
export function* samples(count: number): Generator<string> {
  const pieces = [
    "a",
    "Z",
    "1",
    "9",
    ".",
    "-",
    "_",
    "%",
    "+",
    "@",
    ":",
    "/",
    "//",
    "://",
    "?",
    "#",
    " ",
    "\n",
    "\t",
    "at ",
    "\n    at ",
    "com",
    "x.io",
    "http",
    "https://",
    "123-45-6789",
    "12345678",
    "jane@example.com",
    "=",
    "é",
    "\r",
    "\r\n    at ",
    "\u00a0",
    "\u2028",
    "\u3000",
    "HTTP://",
    "Https://h?q",
    "u:p@",
    "HTTPS://user:pw@h/p",
    '"//',
    "(//u:",
    "p@s",
    "p?s@",
    ":8080/",
    ":p/s@",
    ",",
    '"',
    "'",
    "<",
    "`",
    "[::1]",
    "]",
    ";",
    ",//",
    "u:ab://",
    "#c@",
    ":/",
    " jdbc:pg://",
    "://a:b@c@d/",
    "'s@",
    '"x@',
    '\\"',
    "\\/\\/",
    "\\",
    ":2024#",
    "=",
    " https:/",
    "1pg://",
    "h:/",
    ";j=S",
    ":\\a/",
    "')",
    "''",
  ];
  let seed = 42;
  const next = () => (seed = (seed * 1103515245 + 12345) % 2 ** 31);
  for (let i = 0; i < count; i++) {
    const length = 1 + (next() % 14);
    yield Array.from({ length }, () => pieces[next() % pieces.length]).join("");
  }
}
